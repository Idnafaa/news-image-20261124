# main.py — entrypoint for "The World in One Day — 24 November 2026".
# The poster is rendered by render.py at build time and committed as
# entry.png; this program only copies those exact bytes to /output/entry.png.
# Pure Python 3.13 standard library, no network, fully deterministic.
import os
import shutil
import sys


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    src = os.path.join(here, "entry.png")
    if not os.path.isfile(src):
        print("entry.png missing next to main.py", file=sys.stderr)
        return 1
    out_dir = "/output"
    os.makedirs(out_dir, exist_ok=True)
    dst = os.path.join(out_dir, "entry.png")
    shutil.copyfile(src, dst)
    print("wrote %s (%d bytes)" % (dst, os.path.getsize(dst)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
